export type Lang = "es" | "en" | "mix" | "nah" | "yua" | "quc" | "qvi";

export type LangInfo = {
  code: Lang;
  name: string;      // name in its own language
  label: string;     // name in Spanish, shown under it
  region: string;
  indigenous: boolean;
  speechLocale: string; // locale used for browser speech / voice
};

